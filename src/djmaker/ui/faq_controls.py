class FaqController:
    """Экран статичных вопросов и ответов по функциям DJMAKER."""

    def __init__(self, app: "DJMakerUI") -> None:
        self.app = app

    def show_faq(self) -> None:
        app = self.app
        app._set_navigation_index(8)

        cards = [self.topic_card(icon, title, entries) for icon, title, entries in FAQ_TOPICS]
        faq_list = ft.ListView(
            controls=cards,
            expand=True,
            spacing=COMPACT_UI.space_md,
            padding=0,
        )
        app._replace_content("FAQ", "Ответы на частые вопросы о функциях DJMAKER", faq_list)

    def topic_card(
        self, icon: str, title: str, entries: tuple[tuple[str, str], ...]
    ) -> ft.Control:
        app = self.app
        rows: list[ft.Control] = [
            ft.Row(
                controls=[
                    ft.Icon(icon, color=ft.Colors.PRIMARY),
                    ft.Text(title, size=COMPACT_UI.font_lg, weight=ft.FontWeight.BOLD),
                ]
            ),
        ]
        for question, answer in entries:
            rows.append(ft.Divider(height=1, color=ft.Colors.OUTLINE_VARIANT))
            rows.append(
                ft.Column(
                    controls=[
                        ft.Text(
                            question,
                            size=COMPACT_UI.font_md,
                            weight=ft.FontWeight.BOLD,
                        ),
                        ft.Text(
                            answer,
                            size=COMPACT_UI.font_sm,
                            color=ft.Colors.ON_SURFACE_VARIANT,
                        ),
                    ],
                    spacing=2,
                )
            )
        return app._surface_card(ft.Column(controls=rows, spacing=COMPACT_UI.space_sm))
